class TestPaginationTraversal:
    """Test suite for paginated collection requests using RFC 5988 Link headers."""

    async def test_multi_page_pagination_traversal(
        self, hass: HomeAssistant, aioclient_mock: AiohttpClientMocker
    ) -> None:
        """Test multi-page pagination traversing rel='next' links across pages."""
        session = async_get_clientsession(hass)
        client = CanvasApiClient(TEST_BASE_URL, TEST_ACCESS_TOKEN, session)

        page1_url = f"{TEST_BASE_URL}{ENDPOINT_USERS_OBSERVEES}"
        page2_url = f"{TEST_BASE_URL}/api/v1/users/self/observees?page=2&per_page=100"

        page1_data = [{"id": 1, "name": "Student One"}]
        page2_data = [{"id": 2, "name": "Student Two"}]

        link_header_page1 = build_link_header(
            current_url=page1_url,
            next_url=page2_url,
            first_url=page1_url,
            last_url=page2_url,
        )

        # Register page 2 first (more specific URL) so AiohttpClientMocker prioritizes it
        aioclient_mock.get(
            page2_url,
            json=page2_data,
            headers={},  # Terminal page without Link header
        )
        aioclient_mock.get(
            page1_url,
            json=page1_data,
            headers={HEADER_LINK: link_header_page1},
        )

        observees = await client.async_get_observees()
        assert len(observees) == 2
        assert observees[0].id == 1
        assert observees[0].name == "Student One"
        assert observees[1].id == 2
        assert observees[1].name == "Student Two"
        assert len(aioclient_mock.mock_calls) == 2

    async def test_pagination_stops_on_empty_page(
        self, hass: HomeAssistant, aioclient_mock: AiohttpClientMocker
    ) -> None:
        """Test pagination halts when an empty list payload is encountered."""
        session = async_get_clientsession(hass)
        client = CanvasApiClient(TEST_BASE_URL, TEST_ACCESS_TOKEN, session)

        page1_url = f"{TEST_BASE_URL}{ENDPOINT_USERS_OBSERVEES}"
        aioclient_mock.get(
            page1_url,
            json=[],
            headers={
                HEADER_LINK: f'<{TEST_BASE_URL}/api/v1/users/self/observees?page=2>; rel="next"'
            },
        )

        observees = await client.async_get_observees()
        assert observees == []
        # Halts immediately on empty payload without fetching page 2
        assert len(aioclient_mock.mock_calls) == 1

    async def test_pagination_circular_reference_safeguard(
        self, hass: HomeAssistant, aioclient_mock: AiohttpClientMocker
    ) -> None:
        """Test circular pagination detection prevents infinite loops."""
        session = async_get_clientsession(hass)
        client = CanvasApiClient(TEST_BASE_URL, TEST_ACCESS_TOKEN, session)

        page1_url = f"{TEST_BASE_URL}{ENDPOINT_USERS_OBSERVEES}"
        page2_url = f"{TEST_BASE_URL}/api/v1/users/self/observees?page=2"

        # Page 1 links to Page 2; Page 2 maliciously links back to Page 1
        aioclient_mock.get(
            page2_url,
            json=[{"id": 2, "name": "Student 2"}],
            headers={HEADER_LINK: f'<{page1_url}>; rel="next"'},
        )
        aioclient_mock.get(
            page1_url,
            json=[{"id": 1, "name": "Student 1"}],
            headers={HEADER_LINK: f'<{page2_url}>; rel="next"'},
        )

        observees = await client.async_get_observees()
        assert len(observees) == 2
        assert observees[0].id == 1
        assert observees[1].id == 2
        # Safely stops after detecting page1 was already visited
        assert len(aioclient_mock.mock_calls) == 2

    async def test_pagination_max_pages_limit(
        self, hass: HomeAssistant, aioclient_mock: AiohttpClientMocker
    ) -> None:
        """Test max_pages boundary limits excessive page requests."""
        session = async_get_clientsession(hass)
        client = CanvasApiClient(TEST_BASE_URL, TEST_ACCESS_TOKEN, session)

        endpoint = "/api/v1/courses"
        url1 = f"{TEST_BASE_URL}{endpoint}"
        url2 = f"{TEST_BASE_URL}{endpoint}?page=2"
        url3 = f"{TEST_BASE_URL}{endpoint}?page=3"

        aioclient_mock.get(
            url3,
            json=[{"id": 3}],
            headers={},
        )
        aioclient_mock.get(
            url2,
            json=[{"id": 2}],
            headers={HEADER_LINK: f'<{url3}>; rel="next"'},
        )
        aioclient_mock.get(
            url1,
            json=[{"id": 1}],
            headers={HEADER_LINK: f'<{url2}>; rel="next"'},
        )

        items = await client._request_paginated(endpoint, max_pages=2)
        assert len(items) == 2
        assert items[0]["id"] == 1
        assert items[1]["id"] == 2
        assert len(aioclient_mock.mock_calls) == 2

    async def test_pagination_non_list_payload_safeguard(
        self, hass: HomeAssistant, aioclient_mock: AiohttpClientMocker
    ) -> None:
        """Test pagination terminates cleanly if an unexpected non-list payload is returned."""
