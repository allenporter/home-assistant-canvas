class TestCanvasApiClientInit:
    """Test suite for CanvasApiClient initialization and header preparation."""

    def test_init_url_normalization(self) -> None:
        """Test base URL normalization: trailing slash stripping and scheme inference."""
        session = AsyncMock(spec=aiohttp.ClientSession)

        # Standard HTTPS URL with trailing slash
        client1 = CanvasApiClient(
            "https://canvas.example.edu/", TEST_ACCESS_TOKEN, session
        )
        assert client1.base_url == "https://canvas.example.edu"
        assert client1.access_token == TEST_ACCESS_TOKEN

        # URL with whitespace
        client2 = CanvasApiClient(
            "  https://canvas.example.edu/  ", f"  {TEST_ACCESS_TOKEN}  ", session
        )
        assert client2.base_url == "https://canvas.example.edu"
        assert client2.access_token == TEST_ACCESS_TOKEN

        # URL without scheme defaults to https
        client3 = CanvasApiClient("canvas.example.edu", TEST_ACCESS_TOKEN, session)
        assert client3.base_url == "https://canvas.example.edu"

        # HTTP scheme is preserved
        client4 = CanvasApiClient(
            "http://canvas.local:8080/", TEST_ACCESS_TOKEN, session
        )
        assert client4.base_url == "http://canvas.local:8080"

    def test_init_headers_and_defaults(self) -> None:
        """Test standard headers generated by the client."""
        session = AsyncMock(spec=aiohttp.ClientSession)
        client = CanvasApiClient(
            TEST_BASE_URL,
            TEST_ACCESS_TOKEN,
            session,
            timeout=30,
        )

        headers = client._headers
        assert headers[HEADER_AUTHORIZATION] == f"Bearer {TEST_ACCESS_TOKEN}"
        assert headers[HEADER_ACCEPT] == DEFAULT_ACCEPT_TYPE
        assert headers[HEADER_USER_AGENT] == DEFAULT_USER_AGENT
        assert client._timeout == 30
        assert client.rate_limit_remaining is None

    def test_init_default_timeout(self) -> None:
        """Test default timeout assignment."""
        session = AsyncMock(spec=aiohttp.ClientSession)
        client = CanvasApiClient(TEST_BASE_URL, TEST_ACCESS_TOKEN, session)
        assert client._timeout == API_TIMEOUT


