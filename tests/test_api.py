class TestLinkHeaderParsing:
    """Test suite for RFC 5988 Link header extraction."""

    @pytest.mark.parametrize(
        ("link_header", "expected_next_url"),
        [
            # Single next link with double quotes
            (
                '<https://canvas.example.edu/api/v1/courses?page=2&per_page=100>; rel="next"',
                "https://canvas.example.edu/api/v1/courses?page=2&per_page=100",
            ),
            # Single next link with single quotes
            (
                "<https://canvas.example.edu/api/v1/courses?page=2>; rel='next'",
                "https://canvas.example.edu/api/v1/courses?page=2",
            ),
            # Single next link without quotes
            (
                "<https://canvas.example.edu/api/v1/courses?page=2>; rel=next",
                "https://canvas.example.edu/api/v1/courses?page=2",
            ),
            # Multiple relations (current, next, first, last)
            (
                '<https://canvas.example.edu/api/v1/courses?page=1>; rel="current", '
                '<https://canvas.example.edu/api/v1/courses?page=2>; rel="next", '
                '<https://canvas.example.edu/api/v1/courses?page=1>; rel="first", '
                '<https://canvas.example.edu/api/v1/courses?page=5>; rel="last"',
                "https://canvas.example.edu/api/v1/courses?page=2",
            ),
            # Extra spaces around relation
            (
                '<https://canvas.example.edu/api/v1/courses?page=3> ;  rel = "next" ; title="Next Page"',
                "https://canvas.example.edu/api/v1/courses?page=3",
            ),
            # Terminal page (no rel="next")
            (
                '<https://canvas.example.edu/api/v1/courses?page=5>; rel="current", '
                '<https://canvas.example.edu/api/v1/courses?page=4>; rel="prev", '
                '<https://canvas.example.edu/api/v1/courses?page=1>; rel="first"',
                None,
            ),
            # Empty and None header
            ("", None),
            (None, None),
            # Malformed link headers
            ("not-a-valid-link-header", None),
            ("https://canvas.example.edu/courses; rel=next", None),
            ("<>; rel=next", ""),
        ],
    )
    def test_parse_next_link(
        self, link_header: str | None, expected_next_url: str | None
    ) -> None:
        """Test _parse_next_link correctly extracts next page URLs or returns None."""
        assert _parse_next_link(link_header) == expected_next_url


